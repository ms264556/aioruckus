@pytest.mark.asyncio
async def test_sz_do_remove_guest_passes(create_sz_session, aiohttp_context):
    """Removal resolves keys to user ids and issues a single idList delete."""
    callback, requests, _ = _sz_guest_callback_factory()
    async with create_sz_session() as session:
        _register_sz_guest_routes(aiohttp_context, callback)
        await session.api.do_remove_guest_passes("6ygwR3B2", "J8cjtQM9")

    delete = next((path, body) for path, body in requests if path.endswith("/identity/guestpass"))
    assert delete[1] == {"idList": ["afdfc09e-ef23-4d93-8598-8ed95fe67460", "ab96f27b-1145-4371-85c6-1c1eaa9aff6f"]}

    # the passes are gone from the store
    guests = await session.api.get_guest_passes()
    assert not [g for g in guests if g["key"] in ("6ygwR3B2", "J8cjtQM9")]


