def _sz_guest_callback_factory(initial_guests=None, wlans=None):
    """Stateful REST callback for the SmartZone guest-pass endpoints.

    Serves ``query/wlan``, ``identity/guestpassList``,
    ``identity/guestpass/generate`` and ``DELETE identity/guestpass``,
    recording ``(url, json)`` tuples. The guest store is mutated by
    generates and deletes so the before/after re-list logic works.
    """
    store = {g["id"]: dict(g) for g in (initial_guests if initial_guests is not None else DEFAULT_GUESTS)}
    next_id = [10]
    requests = []

    def json_response(payload: dict, status: int = 200) -> CallbackResult:
        return CallbackResult(
            body=json.dumps(payload),
            status=status,
            headers={"Content-Type": "application/json"},
        )

    def callback(url, **kwargs):
        url_path = url.path
        body = kwargs.get("json") or {}
        requests.append((url_path, body))
        if url_path.endswith("/query/wlan"):
            wlans_list = wlans if wlans is not None else [SZ_WLAN]
            return json_response({"list": wlans_list, "hasMore": False, "totalCount": len(wlans_list)})
        if url_path.endswith("/identity/guestpassList"):
            return json_response({
                "totalCount": len(store), "hasMore": False,
                "firstIndex": 0, "list": list(store.values()),
            })
        if url_path.endswith("/identity/guestpass/generate"):
            for _ in range(body.get("numberOfPasses", 1)):
                pass_id = str(next_id[0])
                next_id[0] += 1
                store[pass_id] = {
                    "id": pass_id,
                    "userId": f"user-{pass_id}",
                    "key": body.get("passValue") or f"KEY{pass_id}",
                    "guestName": body.get("guestName", ""),
                    "remarks": body.get("remarks", ""),
                    "generatedOn": "2026/01/01 00:00:00",
                    "expirationDate": "2026/01/02 00:00:00",
                    "ssid": (body.get("wlan") or {}).get("name", ""),
                    "wlan": body.get("wlan"),
                    "zone": body.get("zone"),
                    "passValidFor": body.get("passValidFor"),
                    "maxDevices": body.get("maxDevices"),
                    "autoGeneratedPassword": body.get("autoGeneratedPassword", True),
                    "passEffectSince": body.get("passEffectSince", "CREATION_TIME"),
                    "passUseDays": 0,
                    "sessionDuration": body.get("sessionDuration"),
                    "domainId": "some-domain",
                    "creatorUsername": "admin",
                    "isDisabled": "NO",
                }
            return json_response({"id": str(next_id[0] - 1)}, status=201)
        if url_path.endswith("/identity/guestpass"):
            for guest_id in body.get("idList", []):
                for key, guest in list(store.items()):
                    if key == guest_id or guest.get("userId") == guest_id:
                        del store[key]
            return CallbackResult(status=204)
        return CallbackResult(body="\n")

    return callback, requests, store


def _register_sz_guest_routes(aiohttp_context, callback):
    """Register the SmartZone guest-pass routes (overriding defaults)."""
    aiohttp_context.post(
        re.compile(r"^https://192\.168\.0\.3:8443/wsg/api/public/v9_0/query/wlan"),
        callback=callback,
    )
    aiohttp_context.post(
        re.compile(r"^https://192\.168\.0\.3:8443/wsg/api/public/v9_0/identity/guestpassList"),
        callback=callback,
    )
    aiohttp_context.post(
        re.compile(r"^https://192\.168\.0\.3:8443/wsg/api/public/v9_0/identity/guestpass/generate"),
        callback=callback,
    )
    aiohttp_context.delete(
        re.compile(r"^https://192\.168\.0\.3:8443/wsg/api/public/v9_0/identity/guestpass"),
        callback=callback,
    )


@pytest.mark.asyncio
async def test_sz_get_guest_passes(create_sz_session, aiohttp_context):
    """Guest passes list via identity/guestpassList with normalized fields."""
    callback, requests, _ = _sz_guest_callback_factory()
    async with create_sz_session() as session:
        _register_sz_guest_routes(aiohttp_context, callback)
        guests = await session.api.get_guest_passes()

    assert len(guests) == 2
    first, second = guests
    assert first["key"] == "6ygwR3B2"
    assert first["id"] == "24cfb9af-4b3f-4d0a-8a92-b2eba022687b"
    assert first["name"] == "guest-name-1"
    assert first["ssid"] == "MyWiFi"
    assert first["created-by"] == "admin"
    assert first["create-time"] == "2015/10/26 10:19:30"
    assert first["expire-time"] == "2015/10/27 10:19:30"
    assert first["duration"] == "1"
    assert first["duration-unit"] == "day"
    assert first["reauth-enabled"] == "true"
    assert first["reauth-interval"] == "3"
    assert first["reauth-interval-unit"] == "day"
    assert first["shared-guestpass"] == "limited"
    assert first["share-number"] == "3"
    assert first["remarks"] == "remark"
    assert second["key"] == "J8cjtQM9"
    assert second["shared-guestpass"] == "unlimited"

    # the list query is scoped to the logged-in domain
    assert requests[0][0].endswith("/identity/guestpassList")
    assert requests[0][1]["filters"] == [{"type": "DOMAIN", "value": "some-domain"}]


@pytest.mark.asyncio
async def test_sz_do_add_guest_passes(create_sz_session, aiohttp_context):
    """A batch create resolves the WLAN/zone and returns only the new passes."""
    callback, requests, _ = _sz_guest_callback_factory()
    async with create_sz_session() as session:
        _register_sz_guest_routes(aiohttp_context, callback)
        created = await session.api.do_add_guest_passes(
            ssid="MyWiFi",
            duration=1,
            duration_unit="day",
            batch_size=2,
            remarks="aioruckus-test",
        )

    assert len(created) == 2
    assert all(g["id"] not in {gid for gid in ("24cfb9af-4b3f-4d0a-8a92-b2eba022687b", "b28ff2cc-e0f6-4e58-b520-46b29be613ea")} for g in created)
    assert all(g["key"] for g in created)
    assert all(g["ssid"] == "MyWiFi" for g in created)
    assert all(g["remarks"] == "aioruckus-test" for g in created)

    generate = next((path, body) for path, body in requests if path.endswith("/identity/guestpass/generate"))
    body = generate[1]
    assert body["numberOfPasses"] == 2
    assert body["guestName"]                       # auto-generated batch name
    assert body["wlan"] == {"id": "wlan-1", "name": "MyWiFi"}
    assert body["zone"] == {"id": "zone-1", "name": "MyZone"}
    assert body["passValidFor"] == {"expirationValue": 1, "expirationUnit": "DAY"}
    assert body["autoGeneratedPassword"] is True
    assert body["passEffectSince"] == "CREATION_TIME"
    assert body["maxDevices"] == {"maxDevicesAllowed": "LIMITED", "maxDevicesNumber": 1}
    assert body["remarks"] == "aioruckus-test"
    assert body["domainId"] == "some-domain"


